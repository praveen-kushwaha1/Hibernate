package com.hibernate.p07_embedded_inheritance.inheritance.mappedsuperclass;

import jakarta.persistence.Entity;
import jakarta.persistence.Table;

@Entity
@Table(name = "mapped_permanent_employee")
public class MappedPermanentEmployee extends BaseEmployee {

    private double bonus;
    private String pfNumber;

    public MappedPermanentEmployee() {
    }

    public MappedPermanentEmployee(String name, String email,
                                  String department, double salary,
                                  double bonus, String pfNumber) {

        super(name, email, department, salary);

        this.bonus = bonus;
        this.pfNumber = pfNumber;
    }

    public double getBonus() {
        return bonus;
    }

    public void setBonus(double bonus) {
        this.bonus = bonus;
    }

    public String getPfNumber() {
        return pfNumber;
    }

    public void setPfNumber(String pfNumber) {
        this.pfNumber = pfNumber;
    }
}

